-- A single denormalised "order line" fact table used by most views below.
DROP VIEW IF EXISTS vw_order_facts;
CREATE VIEW vw_order_facts AS
SELECT
    oi.order_item_id,
    o.order_id,
    o.customer_id,
    o.order_date,
    strftime('%Y-%m', o.order_date) AS order_month,
    CASE CAST(strftime('%w', o.order_date) AS INTEGER)
        WHEN 0 THEN 'Sunday' WHEN 1 THEN 'Monday' WHEN 2 THEN 'Tuesday'
        WHEN 3 THEN 'Wednesday' WHEN 4 THEN 'Thursday' WHEN 5 THEN 'Friday'
        ELSE 'Saturday' END AS order_weekday,
    o.order_status,
    o.payment_method,
    o.discount_code,
    o.shipping_region,
    p.product_id,
    p.product_name,
    p.category,
    oi.quantity,
    oi.unit_price_at_sale,
    oi.discount_pct,
    oi.returned,
    oi.net_revenue,
    (oi.unit_price_at_sale - p.unit_cost) * oi.quantity AS gross_profit,
    c.acquisition_channel,
    c.region AS customer_region,
    c.signup_date
FROM clean_order_items oi
JOIN clean_orders o    ON oi.order_id = o.order_id
JOIN clean_products p  ON oi.product_id = p.product_id
JOIN clean_customers c ON o.customer_id = c.customer_id
WHERE o.order_status != 'Cancelled';   -- cancelled orders carry no revenue

-- ----------------------------------------------------------------------------
-- 1. Monthly revenue & order trend (overall growth + seasonality)
-- ----------------------------------------------------------------------------
DROP VIEW IF EXISTS vw_monthly_trend;
CREATE VIEW vw_monthly_trend AS
SELECT
    order_month,
    COUNT(DISTINCT order_id)                AS orders,
    COUNT(DISTINCT customer_id)              AS unique_customers,
    ROUND(SUM(net_revenue), 2)               AS revenue,
    ROUND(SUM(gross_profit), 2)              AS gross_profit,
    ROUND(SUM(net_revenue) * 1.0 / COUNT(DISTINCT order_id), 2) AS avg_order_value
FROM vw_order_facts
GROUP BY order_month
ORDER BY order_month;

-- ----------------------------------------------------------------------------
-- 2. Category performance (revenue, margin, return rate, YoY growth)
-- ----------------------------------------------------------------------------
DROP VIEW IF EXISTS vw_category_performance;
CREATE VIEW vw_category_performance AS
SELECT
    category,
    SUBSTR(order_month, 1, 4) AS year,
    ROUND(SUM(net_revenue), 2) AS revenue,
    ROUND(SUM(gross_profit), 2) AS gross_profit,
    ROUND(100.0 * SUM(gross_profit) / NULLIF(SUM(net_revenue), 0), 1) AS margin_pct,
    COUNT(DISTINCT order_id) AS orders,
    ROUND(100.0 * SUM(returned) / COUNT(*), 1) AS return_rate_pct
FROM vw_order_facts
GROUP BY category, year
ORDER BY category, year;

-- ----------------------------------------------------------------------------
-- 3. Weekday demand pattern
-- ----------------------------------------------------------------------------
DROP VIEW IF EXISTS vw_weekday_pattern;
CREATE VIEW vw_weekday_pattern AS
SELECT
    order_weekday,
    COUNT(DISTINCT order_id) AS orders,
    ROUND(SUM(net_revenue), 2) AS revenue,
    ROUND(AVG(net_revenue), 2) AS avg_line_value
FROM vw_order_facts
GROUP BY order_weekday;

-- ----------------------------------------------------------------------------
-- 4. Acquisition channel efficiency (spend vs. revenue generated by
--    customers acquired through that channel, monthly)
-- ----------------------------------------------------------------------------
DROP VIEW IF EXISTS vw_channel_efficiency;
CREATE VIEW vw_channel_efficiency AS
WITH channel_revenue AS (
    SELECT
        acquisition_channel AS channel,
        order_month AS month,
        SUM(net_revenue) AS revenue
    FROM vw_order_facts
    GROUP BY acquisition_channel, order_month
)
SELECT
    cr.month,
    cr.channel,
    cr.revenue,
    ms.spend_gbp,
    ROUND(cr.revenue / NULLIF(ms.spend_gbp, 0), 2) AS revenue_per_pound_spent
FROM channel_revenue cr
LEFT JOIN clean_marketing_spend ms
    ON cr.channel = ms.channel AND cr.month = ms.month
ORDER BY cr.month, cr.channel;

-- ----------------------------------------------------------------------------
-- 5. Customer monthly acquisition cohorts + retention (cohort analysis)
-- ----------------------------------------------------------------------------
DROP VIEW IF EXISTS vw_cohort_retention;
CREATE VIEW vw_cohort_retention AS
WITH first_purchase AS (
    SELECT customer_id, MIN(order_month) AS cohort_month
    FROM vw_order_facts
    GROUP BY customer_id
),
activity AS (
    SELECT DISTINCT customer_id, order_month
    FROM vw_order_facts
)
SELECT
    fp.cohort_month,
    a.order_month AS activity_month,
    (
        (CAST(SUBSTR(a.order_month, 1, 4) AS INTEGER) - CAST(SUBSTR(fp.cohort_month, 1, 4) AS INTEGER)) * 12
        + (CAST(SUBSTR(a.order_month, 6, 2) AS INTEGER) - CAST(SUBSTR(fp.cohort_month, 6, 2) AS INTEGER))
    ) AS months_since_first_purchase,
    COUNT(DISTINCT a.customer_id) AS active_customers
FROM activity a
JOIN first_purchase fp ON a.customer_id = fp.customer_id
GROUP BY fp.cohort_month, a.order_month
ORDER BY fp.cohort_month, a.order_month;

-- ----------------------------------------------------------------------------
-- 6. Customer-level RFM inputs (Recency, Frequency, Monetary) as of the
--    last day of the dataset, for a lightweight segmentation in Python
-- ----------------------------------------------------------------------------
DROP VIEW IF EXISTS vw_customer_rfm;
CREATE VIEW vw_customer_rfm AS
SELECT
    customer_id,
    MAX(order_date) AS last_order_date,
    CAST(julianday('2024-12-31') - julianday(MAX(order_date)) AS INTEGER) AS recency_days,
    COUNT(DISTINCT order_id) AS frequency,
    ROUND(SUM(net_revenue), 2) AS monetary,
    acquisition_channel,
    customer_region
FROM vw_order_facts
GROUP BY customer_id;

-- ----------------------------------------------------------------------------
-- 7. Discount code effectiveness
-- ----------------------------------------------------------------------------
DROP VIEW IF EXISTS vw_discount_effectiveness;
CREATE VIEW vw_discount_effectiveness AS
SELECT
    COALESCE(discount_code, 'No Code') AS discount_code,
    COUNT(DISTINCT order_id) AS orders,
    ROUND(SUM(net_revenue), 2) AS revenue,
    ROUND(AVG(net_revenue), 2) AS avg_line_value,
    ROUND(100.0 * SUM(returned) / COUNT(*), 1) AS return_rate_pct
FROM vw_order_facts
GROUP BY discount_code
ORDER BY revenue DESC;
